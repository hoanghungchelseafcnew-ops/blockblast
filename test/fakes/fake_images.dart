/// Factory ảnh mạng giả: không gọi mạng, đếm số lần được gọi.
class FakeNetworkImageFactory {
  FakeNetworkImageFactory({this.fails = false});

  /// Nếu true, provider trả về giải mã lỗi (giả lập tải ảnh hỏng).
  bool fails;

  final List<String> calls = <String>[];

  ImageProvider<Object> call(String url) {
    calls.add(url);
    return MemoryImage(fails ? kBrokenImageBytes : kTransparentPng);
  }
}
